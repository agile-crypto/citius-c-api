void agc_key_info_free(agc_key_info *ki)
{
    if (!ki) return;
    free(ki->name);
    free(ki->key_id);
    free(ki->template_id);
    free(ki->provider);
    free(ki->policy);
    free(ki->public_key);
    free(ki);
}

