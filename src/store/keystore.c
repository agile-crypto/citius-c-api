agc_rc agc_key_info_scope_spec(const agc_key_info *ki, agc_scope_spec *out)
{
    if (!ki || !out) return AGC_ERR_INVALID_ARGUMENT;
    *out = ki->scope_spec;
    return AGC_OK;
}

agc_rc agc_key_info_public_key(const agc_key_info *ki, agc_buf out, size_t *out_len)
{
    if (!ki || !out_len) return AGC_ERR_INVALID_ARGUMENT;
    if (!ki->public_key) return AGC_ERR_INVALID_ARGUMENT;
    *out_len = ki->public_key_len;
    if (out.data == NULL) return AGC_OK;
    if (out.cap < ki->public_key_len) return AGC_ERR_BUFFER_TOO_SMALL;
    memcpy(out.data, ki->public_key, ki->public_key_len);
    return AGC_OK;
}

agc_rc agc_key_info_public_key_format(const agc_key_info *ki, agc_key_format *out)
{
    if (!ki || !out || !ki->has_public_key_format) return AGC_ERR_INVALID_ARGUMENT;
    *out = ki->public_key_format;
    return AGC_OK;
}

