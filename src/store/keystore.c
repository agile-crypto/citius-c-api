/* SPDX-License-Identifier: Apache-2.0
 *
 * keystore.c — in-memory key store backing the stub provider, plus the
 * public agc_key_info handle it produces snapshots into.
 *
 * SCOPING NOTE: a stored key's agc_scope_spec retains only the scalar
 * fields (kind, per-primitive scope enum, security properties) -- the
 * `additional_properties` map<string,string> on the caller's scope_spec is
 * NOT retained across CreateKey. Deep-copying an arbitrary caller-owned
 * kv_list through every layer of a stub store buys little for the cost, and
 * the field carries no semantics this reconciliation exercises. Real
 * fidelity for that one field, if ever needed, is a matter of extending
 * dup_scope_spec_scalars() below.
 */
#define _POSIX_C_SOURCE 200809L /* strdup */
#include "agc_internal.h"
#include "agc_key.h"

#include <pthread.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

/* --------------------------------------------------------------------------
 * Storage model: one name maps to an ascending list of versions. Whole-key
 * fields (policy, lifecycle_state, extractable) live at the name level and
 * apply across every version, matching "RotateKey: new version, same
 * template and policy; previous versions remain usable" and "DeleteKey"
 * acting on the key as a whole rather than one version.
 * -------------------------------------------------------------------------- */

typedef struct key_version_entry {
    uint32_t        version;
    char           *key_id;
    char           *template_id;
    agc_scope_spec  scope_spec;      /* additional_properties always {0,0}: see file header */
    char           *provider;
    agc_timestamp   created_time;
    uint8_t        *secret;
    size_t          secret_len;
    uint8_t        *public_key;      /* NULL for symmetric-shaped scopes */
    size_t          public_key_len;
    int             has_public_key_format;
    agc_key_format  public_key_format;
} key_version_entry;

typedef struct stored_key_name {
    char                    *name;
    char                    *policy;
    agc_timestamp            updated_time;
    int                      extractable;
    agc_key_lifecycle_state  lifecycle_state;
    key_version_entry      **versions;
    size_t                   version_count;
    size_t                   version_cap;
} stored_key_name;

struct agc_keystore {
    pthread_mutex_t     mutex;
    stored_key_name   **items;
    size_t              count;
    size_t              cap;
};

/* --------------------------------------------------------------------------
 * The public opaque handle: an owned snapshot, decoupled from the live
 * store entry so callers may hold it across further store mutations.
 * -------------------------------------------------------------------------- */
struct agc_key_info {
    char                    *name;
    uint32_t                 version;
    char                    *key_id;
    char                    *template_id;
    agc_scope_spec           scope_spec;
    char                    *provider;
    agc_timestamp            created_time;
    agc_timestamp            updated_time;
    char                    *policy;
    int                      extractable;
    agc_key_lifecycle_state  lifecycle_state;
    uint8_t                 *public_key;
    size_t                   public_key_len;
    int                      has_public_key_format;
    agc_key_format           public_key_format;
    /* provider_metadata: always empty in this stub -- no provider-specific
     * metadata is generated by src/stub/. */
};

/* --------------------------------------------------------------------------
 * Lifecycle: attaching to a context via the generic extension-slot mechanism
 * -------------------------------------------------------------------------- */

static void free_version_entry(key_version_entry *v)
{
    if (!v) return;
    free(v->key_id);
    free(v->template_id);
    free(v->provider);
    if (v->secret) { agc_secure_zero(v->secret, v->secret_len); free(v->secret); }
    free(v->public_key);
    free(v);
}

static void free_stored_key_name(stored_key_name *k)
{
    if (!k) return;
    free(k->name);
    free(k->policy);
    for (size_t i = 0; i < k->version_count; i++) free_version_entry(k->versions[i]);
    free(k->versions);
    free(k);
}

static void *keystore_create(void)
{
    struct agc_keystore *ks = calloc(1, sizeof(*ks));
    if (!ks) return NULL;
    pthread_mutex_init(&ks->mutex, NULL);
    return ks;
}

static void keystore_destroy(void *p)
{
    struct agc_keystore *ks = p;
    if (!ks) return;
    for (size_t i = 0; i < ks->count; i++) free_stored_key_name(ks->items[i]);
    free(ks->items);
    pthread_mutex_destroy(&ks->mutex);
    free(ks);
}

static struct agc_keystore *keystore_for(agc_ctx *ctx)
{
    return agc__ctx_get_or_create_ext(ctx, AGC_CTX_EXT_KEYSTORE, keystore_create, keystore_destroy);
}

/* --------------------------------------------------------------------------
 * Internal helpers (no locking -- callers hold ks->mutex)
 * -------------------------------------------------------------------------- */

static stored_key_name *find_locked(struct agc_keystore *ks, const char *name)
{
    for (size_t i = 0; i < ks->count; i++) {
        if (strcmp(ks->items[i]->name, name) == 0) return ks->items[i];
    }
    return NULL;
}

static key_version_entry *latest_version_locked(stored_key_name *k)
{
    return k->version_count ? k->versions[k->version_count - 1] : NULL;
}

static key_version_entry *find_version_locked(stored_key_name *k, uint32_t version)
{
    if (version == 0) return latest_version_locked(k);
    for (size_t i = 0; i < k->version_count; i++) {
        if (k->versions[i]->version == version) return k->versions[i];
    }
    return NULL;
}

static void dup_scope_spec_scalars(const agc_scope_spec *in, agc_scope_spec *out)
{
    memset(out, 0, sizeof(*out));
    if (!in) { out->kind = AGC_SCOPE_KIND_NONE; return; }
    out->struct_size = sizeof(*out);
    out->kind = in->kind;
    out->u = in->u; /* value copy; any kv_list pointers inside are then zeroed below */
    switch (out->kind) {
    case AGC_SCOPE_KIND_SIGNATURE: out->u.signature.additional_properties = (agc_kv_list){0}; break;
    case AGC_SCOPE_KIND_AEAD: out->u.aead.additional_properties = (agc_kv_list){0}; break;
    case AGC_SCOPE_KIND_MAC: out->u.mac.additional_properties = (agc_kv_list){0}; break;
    case AGC_SCOPE_KIND_KEM: out->u.kem.additional_properties = (agc_kv_list){0}; break;
    case AGC_SCOPE_KIND_KEY_AGREEMENT: out->u.key_agreement.additional_properties = (agc_kv_list){0}; break;
    case AGC_SCOPE_KIND_KDF: out->u.kdf.additional_properties = (agc_kv_list){0}; break;
    case AGC_SCOPE_KIND_HASH: out->u.hash.additional_properties = (agc_kv_list){0}; break;
    case AGC_SCOPE_KIND_KEY_WRAPPING: out->u.key_wrapping.additional_properties = (agc_kv_list){0}; break;
    case AGC_SCOPE_KIND_SYMMETRIC_CIPHER: out->u.symmetric_cipher.additional_properties = (agc_kv_list){0}; break;
    case AGC_SCOPE_KIND_GENERIC_SECRET: out->u.generic_secret.additional_properties = (agc_kv_list){0}; break;
    case AGC_SCOPE_KIND_DISK_ENCRYPTION: out->u.disk_encryption.additional_properties = (agc_kv_list){0}; break;
    case AGC_SCOPE_KIND_ASYMMETRIC_ENCRYPTION: out->u.asymmetric_encryption.additional_properties = (agc_kv_list){0}; break;
    default: break;
    }
}

/* Whether a scope kind conventionally implies an asymmetric keypair, for
 * deciding whether the stub generates a "public key" blob alongside the
 * secret. Not a real algorithm decision (there is no real algorithm here) --
 * just enough to exercise agc_key_info_public_key()'s code paths. */
static int scope_kind_is_asymmetric(agc_scope_kind k)
{
    return k == AGC_SCOPE_KIND_SIGNATURE || k == AGC_SCOPE_KIND_KEY_AGREEMENT ||
           k == AGC_SCOPE_KIND_KEM || k == AGC_SCOPE_KIND_ASYMMETRIC_ENCRYPTION;
}

static const char *scope_kind_label(agc_scope_kind k)
{
    switch (k) {
    case AGC_SCOPE_KIND_SIGNATURE: return "signature";
    case AGC_SCOPE_KIND_AEAD: return "aead";
    case AGC_SCOPE_KIND_MAC: return "mac";
    case AGC_SCOPE_KIND_KEM: return "kem";
    case AGC_SCOPE_KIND_KEY_AGREEMENT: return "key-agreement";
    case AGC_SCOPE_KIND_KDF: return "kdf";
    case AGC_SCOPE_KIND_HASH: return "hash";
    case AGC_SCOPE_KIND_KEY_WRAPPING: return "key-wrapping";
    case AGC_SCOPE_KIND_SYMMETRIC_CIPHER: return "symmetric-cipher";
    case AGC_SCOPE_KIND_GENERIC_SECRET: return "generic-secret";
    case AGC_SCOPE_KIND_DISK_ENCRYPTION: return "disk-encryption";
    case AGC_SCOPE_KIND_ASYMMETRIC_ENCRYPTION: return "asymmetric-encryption";
    default: return "unspecified";
    }
}

char *agc__derive_stub_template_id(const agc_scope_spec *scope_spec)
{
    char buf[64];
    snprintf(buf, sizeof(buf), "stub-%s-v1", scope_kind_label(scope_spec ? scope_spec->kind : AGC_SCOPE_KIND_NONE));
    return strdup(buf);
}

static agc_timestamp now_timestamp(void)
{
    agc_timestamp ts;
    ts.seconds = (int64_t)time(NULL);
    ts.nanos = 0;
    ts.present = 1;
    return ts;
}

static agc_key_info *snapshot(const stored_key_name *k, const key_version_entry *v)
{
    struct agc_key_info *ki = calloc(1, sizeof(*ki));
    if (!ki) return NULL;
    ki->name = strdup(k->name);
    ki->version = v->version;
    ki->key_id = strdup(v->key_id);
    ki->template_id = strdup(v->template_id);
    dup_scope_spec_scalars(&v->scope_spec, &ki->scope_spec);
    ki->provider = strdup(v->provider);
    ki->created_time = v->created_time;
    ki->updated_time = k->updated_time;
    ki->policy = strdup(k->policy ? k->policy : "");
    ki->extractable = k->extractable;
    ki->lifecycle_state = k->lifecycle_state;
    if (v->public_key_len) {
        ki->public_key = malloc(v->public_key_len);
        if (ki->public_key) memcpy(ki->public_key, v->public_key, v->public_key_len);
        ki->public_key_len = v->public_key_len;
    }
    ki->has_public_key_format = v->has_public_key_format;
    ki->public_key_format = v->public_key_format;
    return ki;
}

/* --------------------------------------------------------------------------
 * Store operations used by src/services/key.c
 * -------------------------------------------------------------------------- */

agc_rc agc__keystore_create_key(agc_ctx *ctx, const char *name, const char *policy,
                                 const agc_scope_spec *scope_spec, const char *template_id,
                                 agc_key_info **out_key)
{
    struct agc_keystore *ks = keystore_for(ctx);
    if (!ks) return AGC_ERR_OUT_OF_MEMORY;

    pthread_mutex_lock(&ks->mutex);
    if (find_locked(ks, name)) {
        pthread_mutex_unlock(&ks->mutex);
        return AGC_ERR_ALREADY_EXISTS;
    }

    stored_key_name *k = calloc(1, sizeof(*k));
    key_version_entry *v = calloc(1, sizeof(*v));
    if (!k || !v) {
        free(k); free(v);
        pthread_mutex_unlock(&ks->mutex);
        return AGC_ERR_OUT_OF_MEMORY;
    }
    k->name = strdup(name);
    k->policy = strdup(policy ? policy : "");
    k->updated_time = now_timestamp();
    k->extractable = 1;
    k->lifecycle_state = AGC_KEY_LIFECYCLE_STATE_ACTIVE;

    v->version = 1;
    char key_id_buf[48];
    snprintf(key_id_buf, sizeof(key_id_buf), "kid-%p-%ld", (void *)v, (long)time(NULL));
    v->key_id = strdup(key_id_buf);
    v->template_id = template_id ? strdup(template_id) : agc__derive_stub_template_id(scope_spec);
    dup_scope_spec_scalars(scope_spec, &v->scope_spec);
    v->provider = strdup("stub");
    v->created_time = now_timestamp();
    v->secret_len = 32;
    v->secret = malloc(v->secret_len);
    if (!v->secret || agc__stub_random(v->secret, v->secret_len) != AGC_OK) {
        free_stored_key_name(k);
        free_version_entry(v);
        pthread_mutex_unlock(&ks->mutex);
        return AGC_ERR_INTERNAL;
    }
    if (scope_spec && scope_kind_is_asymmetric(scope_spec->kind)) {
        v->public_key_len = 32;
        v->public_key = malloc(v->public_key_len);
        agc__stub_random(v->public_key, v->public_key_len);
        v->has_public_key_format = 1;
        v->public_key_format = AGC_KEY_FORMAT_RAW;
    }

    k->versions = malloc(sizeof(*k->versions));
    k->versions[0] = v;
    k->version_count = 1;
    k->version_cap = 1;

    if (ks->count == ks->cap) {
        size_t new_cap = ks->cap ? ks->cap * 2 : 8;
        stored_key_name **grown = realloc(ks->items, new_cap * sizeof(*grown));
        if (!grown) {
            free_stored_key_name(k);
            pthread_mutex_unlock(&ks->mutex);
            return AGC_ERR_OUT_OF_MEMORY;
        }
        ks->items = grown;
        ks->cap = new_cap;
    }
    ks->items[ks->count++] = k;

    *out_key = snapshot(k, v);
    pthread_mutex_unlock(&ks->mutex);
    return *out_key ? AGC_OK : AGC_ERR_OUT_OF_MEMORY;
}

agc_rc agc__keystore_read(agc_ctx *ctx, const char *name, uint32_t version, agc_key_info **out_key)
{
    struct agc_keystore *ks = keystore_for(ctx);
    if (!ks) return AGC_ERR_OUT_OF_MEMORY;

    pthread_mutex_lock(&ks->mutex);
    stored_key_name *k = find_locked(ks, name);
    if (!k) { pthread_mutex_unlock(&ks->mutex); return AGC_ERR_CRYPTO_KEY_NOT_FOUND; }
    key_version_entry *v = find_version_locked(k, version);
    if (!v) { pthread_mutex_unlock(&ks->mutex); return AGC_ERR_CRYPTO_KEY_VERSION_MISMATCH; }
    *out_key = snapshot(k, v);
    pthread_mutex_unlock(&ks->mutex);
    return *out_key ? AGC_OK : AGC_ERR_OUT_OF_MEMORY;
}

agc_rc agc__keystore_list(agc_ctx *ctx, agc_key_lifecycle_state filter_state,
                           agc_key_info ***out_items, size_t *out_count)
{
    struct agc_keystore *ks = keystore_for(ctx);
    if (!ks) return AGC_ERR_OUT_OF_MEMORY;

    pthread_mutex_lock(&ks->mutex);
    agc_key_info **items = ks->count ? calloc(ks->count, sizeof(*items)) : NULL;
    size_t n = 0;
    for (size_t i = 0; i < ks->count; i++) {
        stored_key_name *k = ks->items[i];
        if (filter_state != AGC_KEY_LIFECYCLE_STATE_UNSPECIFIED && k->lifecycle_state != filter_state) continue;
        key_version_entry *v = latest_version_locked(k);
        if (!v) continue;
        items[n++] = snapshot(k, v);
    }
    pthread_mutex_unlock(&ks->mutex);
    *out_items = items;
    *out_count = n;
    return AGC_OK;
}

agc_rc agc__keystore_delete(agc_ctx *ctx, const char *name)
{
    struct agc_keystore *ks = keystore_for(ctx);
    if (!ks) return AGC_ERR_OUT_OF_MEMORY;

    pthread_mutex_lock(&ks->mutex);
    stored_key_name *k = find_locked(ks, name);
    if (!k) { pthread_mutex_unlock(&ks->mutex); return AGC_ERR_CRYPTO_KEY_NOT_FOUND; }
    /* Zeroize every version's secret; retain the record (DESTROYED state)
     * for audit, per NIST SP 800-57 §8.3 -- the proto's DeleteKeyRequest
     * has no remove_metadata field (RFC-05), so there is no "purge" path. */
    for (size_t i = 0; i < k->version_count; i++) {
        key_version_entry *v = k->versions[i];
        if (v->secret) agc_secure_zero(v->secret, v->secret_len);
    }
    k->lifecycle_state = (k->lifecycle_state == AGC_KEY_LIFECYCLE_STATE_COMPROMISED)
                             ? AGC_KEY_LIFECYCLE_STATE_DESTROYED_COMPROMISED
                             : AGC_KEY_LIFECYCLE_STATE_DESTROYED;
    k->updated_time = now_timestamp();
    pthread_mutex_unlock(&ks->mutex);
    return AGC_OK;
}

agc_rc agc__keystore_rotate(agc_ctx *ctx, const char *name, agc_key_info **out_new_key)
{
    struct agc_keystore *ks = keystore_for(ctx);
    if (!ks) return AGC_ERR_OUT_OF_MEMORY;

    pthread_mutex_lock(&ks->mutex);
    stored_key_name *k = find_locked(ks, name);
    if (!k) { pthread_mutex_unlock(&ks->mutex); return AGC_ERR_CRYPTO_KEY_NOT_FOUND; }
    key_version_entry *prev = latest_version_locked(k);

    key_version_entry *v = calloc(1, sizeof(*v));
    v->version = prev->version + 1;
    char key_id_buf[48];
    snprintf(key_id_buf, sizeof(key_id_buf), "kid-%p-%ld", (void *)v, (long)time(NULL));
    v->key_id = strdup(key_id_buf);
    v->template_id = strdup(prev->template_id);
    dup_scope_spec_scalars(&prev->scope_spec, &v->scope_spec);
    v->provider = strdup(prev->provider);
    v->created_time = now_timestamp();
    v->secret_len = prev->secret_len;
    v->secret = malloc(v->secret_len);
    agc__stub_random(v->secret, v->secret_len);
    if (prev->public_key_len) {
        v->public_key_len = prev->public_key_len;
        v->public_key = malloc(v->public_key_len);
        agc__stub_random(v->public_key, v->public_key_len);
        v->has_public_key_format = prev->has_public_key_format;
        v->public_key_format = prev->public_key_format;
    }

    if (k->version_count == k->version_cap) {
        size_t new_cap = k->version_cap * 2;
        key_version_entry **grown = realloc(k->versions, new_cap * sizeof(*grown));
        k->versions = grown;
        k->version_cap = new_cap;
    }
    k->versions[k->version_count++] = v;
    k->updated_time = now_timestamp();

    *out_new_key = snapshot(k, v);
    pthread_mutex_unlock(&ks->mutex);
    return *out_new_key ? AGC_OK : AGC_ERR_OUT_OF_MEMORY;
}

agc_rc agc__keystore_transform(agc_ctx *ctx, const char *name, int retain_key_bytes,
                                const agc_scope_spec *scope_spec, const char *template_id,
                                agc_key_info **out_key)
{
    struct agc_keystore *ks = keystore_for(ctx);
    if (!ks) return AGC_ERR_OUT_OF_MEMORY;

    pthread_mutex_lock(&ks->mutex);
    stored_key_name *k = find_locked(ks, name);
    if (!k) { pthread_mutex_unlock(&ks->mutex); return AGC_ERR_CRYPTO_KEY_NOT_FOUND; }
    key_version_entry *prev = latest_version_locked(k);

    if (retain_key_bytes) {
        /* The stub has no real cross-algorithm material-compatibility
         * notion; retaining bytes is only meaningful if the scope kind is
         * unchanged. */
        if (scope_spec && scope_spec->kind != prev->scope_spec.kind) {
            pthread_mutex_unlock(&ks->mutex);
            return AGC_ERR_CRYPTO_INCOMPATIBLE_PARAMETERS;
        }
    }

    key_version_entry *v = calloc(1, sizeof(*v));
    v->version = prev->version + 1;
    char key_id_buf[48];
    snprintf(key_id_buf, sizeof(key_id_buf), "kid-%p-%ld", (void *)v, (long)time(NULL));
    v->key_id = strdup(key_id_buf);
    v->template_id = template_id ? strdup(template_id)
                                  : agc__derive_stub_template_id(scope_spec ? scope_spec : &prev->scope_spec);
    dup_scope_spec_scalars(scope_spec ? scope_spec : &prev->scope_spec, &v->scope_spec);
    v->provider = strdup(prev->provider);
    v->created_time = now_timestamp();
    v->secret_len = prev->secret_len;
    v->secret = malloc(v->secret_len);
    if (retain_key_bytes) memcpy(v->secret, prev->secret, prev->secret_len);
    else agc__stub_random(v->secret, v->secret_len);

    if (k->version_count == k->version_cap) {
        size_t new_cap = k->version_cap * 2;
        key_version_entry **grown = realloc(k->versions, new_cap * sizeof(*grown));
        k->versions = grown;
        k->version_cap = new_cap;
    }
    k->versions[k->version_count++] = v;
    k->updated_time = now_timestamp();

    *out_key = snapshot(k, v);
    pthread_mutex_unlock(&ks->mutex);
    return *out_key ? AGC_OK : AGC_ERR_OUT_OF_MEMORY;
}

agc_rc agc__keystore_update_policy(agc_ctx *ctx, const char *name, const char *new_policy,
                                    agc_key_info **out_key)
{
    struct agc_keystore *ks = keystore_for(ctx);
    if (!ks) return AGC_ERR_OUT_OF_MEMORY;

    pthread_mutex_lock(&ks->mutex);
    stored_key_name *k = find_locked(ks, name);
    if (!k) { pthread_mutex_unlock(&ks->mutex); return AGC_ERR_CRYPTO_KEY_NOT_FOUND; }
    free(k->policy);
    k->policy = strdup(new_policy ? new_policy : "");
    k->updated_time = now_timestamp();
    key_version_entry *v = latest_version_locked(k);
    *out_key = snapshot(k, v);
    pthread_mutex_unlock(&ks->mutex);
    return *out_key ? AGC_OK : AGC_ERR_OUT_OF_MEMORY;
}

agc_rc agc__keystore_update_state(agc_ctx *ctx, const char *name, agc_key_lifecycle_state target,
                                   agc_key_info **out_key)
{
    struct agc_keystore *ks = keystore_for(ctx);
    if (!ks) return AGC_ERR_OUT_OF_MEMORY;

    pthread_mutex_lock(&ks->mutex);
    stored_key_name *k = find_locked(ks, name);
    if (!k) { pthread_mutex_unlock(&ks->mutex); return AGC_ERR_CRYPTO_KEY_NOT_FOUND; }
    k->lifecycle_state = target;
    k->updated_time = now_timestamp();
    key_version_entry *v = latest_version_locked(k);
    *out_key = snapshot(k, v);
    pthread_mutex_unlock(&ks->mutex);
    return *out_key ? AGC_OK : AGC_ERR_OUT_OF_MEMORY;
}

agc_rc agc__keystore_export(agc_ctx *ctx, const char *name, uint8_t **out_material, size_t *out_len)
{
    struct agc_keystore *ks = keystore_for(ctx);
    if (!ks) return AGC_ERR_OUT_OF_MEMORY;

    pthread_mutex_lock(&ks->mutex);
    stored_key_name *k = find_locked(ks, name);
    if (!k) { pthread_mutex_unlock(&ks->mutex); return AGC_ERR_CRYPTO_KEY_NOT_FOUND; }
    if (!k->extractable) { pthread_mutex_unlock(&ks->mutex); return AGC_ERR_CRYPTO_KEY_NOT_EXPORTABLE; }
    key_version_entry *v = latest_version_locked(k);
    *out_material = malloc(v->secret_len);
    if (*out_material) memcpy(*out_material, v->secret, v->secret_len);
    *out_len = v->secret_len;
    pthread_mutex_unlock(&ks->mutex);
    return *out_material ? AGC_OK : AGC_ERR_OUT_OF_MEMORY;
}

agc_rc agc__keystore_import(agc_ctx *ctx, const char *name, const char *policy,
                             agc_slice key_material, const char *template_id, agc_key_info **out_key)
{
    struct agc_keystore *ks = keystore_for(ctx);
    if (!ks) return AGC_ERR_OUT_OF_MEMORY;

    pthread_mutex_lock(&ks->mutex);
    if (find_locked(ks, name)) { pthread_mutex_unlock(&ks->mutex); return AGC_ERR_ALREADY_EXISTS; }

    stored_key_name *k = calloc(1, sizeof(*k));
    key_version_entry *v = calloc(1, sizeof(*v));
    k->name = strdup(name);
    k->policy = strdup(policy ? policy : "");
    k->updated_time = now_timestamp();
    k->extractable = 1;
    k->lifecycle_state = AGC_KEY_LIFECYCLE_STATE_ACTIVE;

    v->version = 1;
    char key_id_buf[48];
    snprintf(key_id_buf, sizeof(key_id_buf), "kid-%p-%ld", (void *)v, (long)time(NULL));
    v->key_id = strdup(key_id_buf);
    v->template_id = strdup(template_id);
    v->scope_spec.kind = AGC_SCOPE_KIND_NONE; /* imported: no intent was declared */
    v->provider = strdup("stub");
    v->created_time = now_timestamp();
    v->secret_len = key_material.len;
    v->secret = malloc(key_material.len ? key_material.len : 1);
    if (key_material.len) memcpy(v->secret, key_material.data, key_material.len);

    k->versions = malloc(sizeof(*k->versions));
    k->versions[0] = v;
    k->version_count = 1;
    k->version_cap = 1;

    if (ks->count == ks->cap) {
        size_t new_cap = ks->cap ? ks->cap * 2 : 8;
        ks->items = realloc(ks->items, new_cap * sizeof(*ks->items));
        ks->cap = new_cap;
    }
    ks->items[ks->count++] = k;

    *out_key = snapshot(k, v);
    pthread_mutex_unlock(&ks->mutex);
    return *out_key ? AGC_OK : AGC_ERR_OUT_OF_MEMORY;
}

